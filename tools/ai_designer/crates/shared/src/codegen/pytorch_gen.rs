fn sanitize_class_name(raw: &str) -> String {
    let parts: Vec<&str> = raw.split('_').collect();
    let mut s = String::new();
    for p in parts {
        if let Some(c) = p.chars().next() {
            s.push_str(&c.to_uppercase().to_string());
            s.push_str(&p[1..]);
        }
    }
    if s.is_empty() {
        "CustomAiModel".to_string()
    } else {
        s
    }
}
